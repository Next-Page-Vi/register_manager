// Regenerates src/api/openapi.json (from the Go server) and
// src/api/schema.d.ts (via openapi-typescript) and constraints.ts. With --check, fails when the
// committed files are out of date.
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const here = dirname(fileURLToPath(import.meta.url))
const web = join(here, '..')
const repo = join(web, '..')
const specPath = join(web, 'src/api/openapi.json')
const typesPath = join(web, 'src/api/schema.d.ts')
const constraintsPath = join(web, 'src/api/constraints.ts')
const check = process.argv.includes('--check')

const spec = execFileSync('go', ['run', './cmd/server', 'openapi'], {
  cwd: repo,
  encoding: 'utf8',
  env: { ...process.env, CGO_ENABLED: '0' },
  maxBuffer: 64 * 1024 * 1024,
})
const document = JSON.parse(spec)
const ast = await openapiTS(document)
const types = '// Generated by scripts/gen-api.mjs from the Go server. Do not edit.\n' + astToString(ast)
const policy = Object.fromEntries(Object.entries(document.components.schemas.Policy.properties).map(([key, field]) => {
  if (typeof field.minimum !== 'number' || typeof field.maximum !== 'number') {
    throw new Error(`Policy.${key} must declare both numeric bounds`)
  }
  return [key, { min: field.minimum, max: field.maximum, nullable: Array.isArray(field.type) && field.type.includes('null') }]
}))
const constraints = '// Generated by scripts/gen-api.mjs. Do not edit.\n' +
  `export const policyConstraints = ${JSON.stringify(policy, null, 2)} as const\n`

if (check) {
  const same = (p, s) => existsSync(p) && readFileSync(p, 'utf8') === s
  if (!same(specPath, spec) || !same(typesPath, types) || !same(constraintsPath, constraints)) {
    console.error('API types are out of date: run `pnpm gen:api` and commit the result.')
    process.exit(1)
  }
  console.log('API types are up to date.')
} else {
  writeFileSync(specPath, spec)
  writeFileSync(typesPath, types)
  writeFileSync(constraintsPath, constraints)
  console.log('Wrote OpenAPI, TypeScript types and Policy constraints.')
}
